#!/usr/bin/env bash
# End-to-end on the compose topology: the CMI image against PostgreSQL, driven from outside by
# tests/e2e. From nothing each run: build image -> postgres -> migrations, service login, tenant ->
# CMI container -> tests -> tear down (KEEP=1 leaves it running).
#   HOST=1   also start the idp-host image (built in the idp-host repository: deploy/build.sh idp-host:dev
#            and deploy/fixtures/build-fakemodel.sh) with a config that points at this CMI, so the test
#            proves ADR-0001 D10 / HOST D32 between real processes: a release with context.cmi = true
#            runs with a ContextPackage from here and records its id.
set -euo pipefail
cd "$(dirname "$0")/.."
ENVF=.local/compose.env
C=(docker compose -f deploy/compose.yaml --env-file "$ENVF" --profile tools --profile host-tools)
HOST="${HOST:-0}"
[[ "$HOST" == 1 ]] && C+=(--profile host)
CMI=http://127.0.0.1:8550
HOSTURL=http://127.0.0.1:8450
CURL=(curl -sf --noproxy '*')
mkdir -p .local
umask 077
if [[ ! -f "$ENVF" ]]; then
  { echo "IDP_PG_OWNER_PASSWORD=$(openssl rand -hex 16)"
    echo "IDP_APP_DB_PASSWORD=$(openssl rand -hex 16)"
    echo "IDP_HOST_DB_PASSWORD=$(openssl rand -hex 16)"
    echo "IDP_DEV_SECRET=$(openssl rand -hex 32)"
    echo "IDP_HOST_CREDENTIAL_KEY=$(openssl rand -hex 32)"; } > "$ENVF"
fi
set -a; source "$ENVF"; set +a

if [[ "$HOST" == 1 ]]; then
  for img in "${IDP_HOST_IMAGE:-idp-host:dev}" "${IDP_FAKEMODEL_IMAGE:-idp-host-fakemodel:dev}"; do
    docker image inspect "$img" >/dev/null 2>&1 || { echo "BLOCKED: image $img missing (build it in the idp-host repository)" >&2; exit 2; }
  done
fi
bash deploy/build.sh idp-cmi:dev
"${C[@]}" down -v --remove-orphans >/dev/null 2>&1 || true
cleanup() { [[ "${KEEP:-0}" == 1 ]] || "${C[@]}" down -v --remove-orphans >/dev/null 2>&1; }
trap cleanup EXIT

umask 022
# placeholders so the HOST containers' bind mounts exist before the real content is known
printf 'pending\n' > .local/cmi.key; chmod 644 .local/cmi.key
: > .local/host.yaml; chmod 644 .local/host.yaml
umask 077

"${C[@]}" up -d --wait postgres
"${C[@]}" exec -T postgres psql -U postgres -q -c 'CREATE DATABASE idp_cmi' >/dev/null
"${C[@]}" run --rm -T cmi-admin migrate
"${C[@]}" run --rm -T cmi-admin ensure-login idp_cmi_svc
TENANT="$("${C[@]}" run --rm -T cmi-admin seed-tenant acme | sed -n 's/^TENANT_ID=//p')"
[[ -n "$TENANT" ]] || { echo "BLOCKED: no tenant" >&2; exit 2; }
"${C[@]}" up -d cmi
for _ in $(seq 1 60); do "${CURL[@]}" -o /dev/null "$CMI/healthz" && break; sleep 0.5; done

if [[ "$HOST" == 1 ]]; then
  # the HOST's own credential at the CMI: a cmi-reader token for the subject idp-host (static mode)
  HOSTKEY="$("${C[@]}" run --rm -T cmi-admin dev-token "$TENANT" idp-host cmi-reader)"
  umask 022
  printf '%s\n' "$HOSTKEY" > .local/cmi.key; chmod 644 .local/cmi.key
  cat > .local/host.yaml <<YAML
# generated by deploy/e2e.sh (DEV ONLY)
providers:
  - name: local
    kind: openai
    baseUrl: http://fakemodel:18080/v1
    insecure: true
cmi:
  endpoint: http://cmi:8550
  auth: {mode: static, apiKeyFile: /etc/idp/cmi.key}
YAML
  umask 077
  "${C[@]}" exec -T postgres psql -U postgres -q -c 'CREATE DATABASE idp_host' >/dev/null
  "${C[@]}" run --rm -T host-admin migrate
  "${C[@]}" run --rm -T host-admin ensure-login idp_host_svc
  HTENANT="$("${C[@]}" run --rm -T host-admin seed-tenant acme "$TENANT" | sed -n 's/^TENANT_ID=//p')"
  [[ "$HTENANT" == "$TENANT" ]] || { echo "BLOCKED: HOST tenant $HTENANT != CMI tenant $TENANT" >&2; exit 2; }
  "${C[@]}" up -d fakemodel host host-worker
  for _ in $(seq 1 60); do "${CURL[@]}" -o /dev/null "$HOSTURL/healthz" && break; sleep 0.5; done
  "${CURL[@]}" -o /dev/null "$HOSTURL/healthz" || { "${C[@]}" logs --tail 20 host host-worker; echo "BLOCKED: the HOST did not come up (is idp-host:dev built from a source with the cmi config, HOST ADR-0001 D32?)" >&2; exit 2; }
fi

echo "published ports: $(docker ps --filter label=com.docker.compose.project=idp-cmi-go --format '{{.Ports}}' | tr ',' '\n' | grep -- '->' | sed 's/^ *//' | sort -u | tr '\n' ' ')"
set +e
IDP_E2E_CMI="$CMI" IDP_E2E_CMI_TENANT="$TENANT" IDP_E2E_CMI_SECRET="$IDP_DEV_SECRET" IDP_E2E_CMI_METRICS=http://127.0.0.1:9565/metrics \
IDP_E2E_HOST="$([[ "$HOST" == 1 ]] && echo "$HOSTURL")" IDP_E2E_HOST_SECRET="$IDP_DEV_SECRET" \
  go test -count=1 -v -run '^TestComposeCMI$' ./tests/e2e/
status=$?
set -e
[[ $status == 0 ]] || "${C[@]}" logs --tail 40 cmi host host-worker 2>/dev/null
exit $status
